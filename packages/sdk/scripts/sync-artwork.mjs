import {writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

/*
 * Copies the Learn course's illustration data into the SDK.
 *
 * The course (jinnie-web/learn/assets/artwork.js) is the one place the
 * drawings are authored; the app renders the same strings through
 * react-native-svg so both surfaces show one set of pictures. Run after the
 * artwork changes and commit the result:
 *   node scripts/sync-artwork.mjs [path-to-jinnie-web]
 */
const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(process.argv[2] ?? join(here, '../../../../jinnie-web'));
const {artwork, plates} = await import(pathToFileURL(join(web, 'learn/assets/artwork.js')).href);

// The character is a bitmap the course serves itself; everything else is vector.
const ids = Object.keys(artwork).filter(id => !artwork[id].includes('<image'));
const entry = (id, value) => `  ${id}: ${JSON.stringify(value)},`;
const out = `// Generated by scripts/sync-artwork.mjs from jinnie-web/learn/assets/artwork.js. Do not edit.
// 120-unit grid, indigo outlines, tonal plates and lamp-gold details.
export const artwork = {
${ids.map(id => entry(id, artwork[id])).join('\n')}
} as const;

export const plates: Partial<Record<keyof typeof artwork, string>> = {
${ids.filter(id => plates[id]).map(id => entry(id, plates[id])).join('\n')}
};
`;
writeFileSync(join(here, '../src/artwork.generated.ts'), out);
console.log(`${ids.length} illustrations written to src/artwork.generated.ts`);
